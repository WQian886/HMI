// 【为什么单独一个文件,而不是写在 hmi.cpp 里】
//   同 ProtocolAvailabilityUi 的理由,一模一样的坑:
//   菜单写在 hmi.cpp 里,测试就只能把代码【复制一份】到测试文件跑 ——
//   测的是副本。hmi.cpp 里那份被改错了(少加一个菜单、连错槽),
//   测试照样全绿。
//   而"菜单连错槽"的后果比协议置灰严重得多:
//     点"打开工程"弹出的是"保存工程"对话框 —— 用户照着填,
//     可能把当前配置覆盖到一个不相关的文件上,而且【看不出发生了什么】。
//   抽出来之后 hmi.cpp 和测试调的是同一个函数,测试绿了才有意义。
//
// 文件职责:把已存在的功能挂成菜单项(工程/运行/画面/报警/数据/帮助)。
//   【不负责实现功能】每个菜单项都 connect 到 hmi 里已有的槽,
//   这里只决定"叫什么、放在哪个菜单、连到谁"。
//
// 【为什么菜单项不新建功能】
//   一个功能的实现只应有一份。菜单和按钮如果各写一份,
//   改一处忘一处,两边行为就分叉 ——
//   而"按钮能用菜单点不了"这种 bug 极难被发现(没有测试能同时覆盖两边)。
//
// 关联:hmi.cpp buildMenus() / onShowCapabilities()
// ============================================================================

#pragma once

#include <QStringList>

class QMenuBar;
class QObject;

namespace qwhmi::ui {

// 在 bar 上搭建完整菜单。返回【没连上的菜单项】列表,空列表 = 全部接好了。
//   QObject* receiver —— 菜单项 connect 的接收者(hmi 实例)
//   槽函数一律通过 receiver 上已有的槽触发,本函数不新增行为。
//
// 【为什么参数是 QObject* 而不是具体类型】
//   菜单项要 connect 到 20 多个槽。如果这里声明具体类型,
//   就会把 hmi 类整个拉进来,而 hmi 依赖 uic 生成的 ui_*.h ——
//   测试侧就编不过了(测试链的是 hmi_core,不含主程序)。
//   传 QObject* + 在这里用 connect(QObject*, ...) 的形式,依赖就断在编译期之外。
//
// 【★ 为什么把失败列表返回出来,而不在这里吞掉】
//   connect 用了字符串槽名,拼错时【不报错、不崩、只是点了没反应】。
//   测试能查"接到了对的那个槽",但用的是假接收者 ——
//   真正跑起来时 receiver 是 hmi,而 hmi 有没有这个槽只有它的元方法表知道。
//   所以生产代码必须自己喊出来:失败就 qWarning 一行,
//   让"槽名对不上"从"用户点了没反应"变成"启动日志里一行黄字"。
//   返回空列表(而不是 void)就是把这份喊话的权力交回给调用方。
//
// 【可重复调用】每次重建会先 clear 掉旧菜单项,不会叠加出两层"工程"。
QStringList buildApplicationMenu(QMenuBar* bar, QObject* receiver);

} // namespace qwhmi::ui
